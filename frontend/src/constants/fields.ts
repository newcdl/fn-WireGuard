/**
 * 配置项元数据中心。
 *
 * 设计目标：让完全不懂网络的用户也能看懂每一项是在做什么。
 * 每个字段统一提供四段信息：
 *   what   —— 这是什么（一句话说清）
 *   why    —— 什么时候需要改它 / 适用场景
 *   effect —— 改完会发生什么
 *   risk   —— 需要谨慎的地方（可选）
 * 另外提供 examples（具体取值 + 案例）与 preset（场景化一键配置）。
 */

export interface FieldExample {
  title: string
  value: string
  desc: string
}

export interface FieldMeta {
  label: string
  hint?: string
  what: string
  why?: string
  effect?: string
  risk?: string
  examples?: FieldExample[]
}

